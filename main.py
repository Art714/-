    @staticmethod
    def _normalize(text: str) -> str:
        """Приводит текст к нижнему регистру, убирает лишние пробелы,
        нормализует похожие буквы (укр./лат. → рус.)."""
        text = text.lower().strip()
        replacements = {
            "і": "и", "ї": "и", "є": "е", "ґ": "г",
            "ё": "е",
            "’": "'", "‘": "'", "“": '"', "”": '"',
        }
        for k, v in replacements.items():
            text = text.replace(k, v)
        return re.sub(r"\s+", " ", text)

    def _detect_language(self, text: str) -> str:
        """Определяет язык: 'ru' или 'en'. Учитывает укр. буквы как русские."""
        t = text.lower()
        ru_chars = len(re.findall(r"[а-яёіїєґ]", t))
        en_chars = len(re.findall(r"[a-z]", t))
        if en_chars > ru_chars:
            return "en"
        return "ru"

