    def bot_response(self, message: str, history) -> str:
        lang = self._detect_language(message)
        user_gender = self._detect_user_gender(message)

        bot_gender = "male"
        t_norm = self._normalize(message)
        if "ботесса" in t_norm or "ботя" in t_norm or "она бот" in t_norm:
            bot_gender = "female"

        message_lower = self._normalize(message)
        friendly = self.get_friendly_response(message_lower, lang)

        # ── Сарказм ──
        sarcastic = self._is_sarcastic(message_lower)
        if sarcastic and not self._is_serious(message_lower) and not self._is_laughing(message_lower):
            return self._get_sarcastic_response(message, lang)

        in_game_guess = (
            self.game_active
            and self.current_character is not None
            and message_lower not in ("игра", "подсказка", "hint", "game")
            and len(message_lower.split()) <= 6
            and not self._is_laughing(message_lower)
            and not self._is_serious(message_lower)
            and friendly is None
        )

        emotion = None
        if not in_game_guess:
            emotion = self.detect_emotion(message_lower)

        if emotion == "питомцы_проблема":
            return self._build_absurd_response(message_lower)

        if emotion in ("болезнь", "самоповреждение", "опасность", "потеря", "потеря_питомца", "сочувствие_другу"):
            empathy = self.get_empathy_response(emotion, lang)
            if empathy:
                return empathy
            if lang == "en":
                return random.choice(self.p.FALLBACK_RESPONSES_EN)

        if emotion in ("грусть", "тревога", "злость", "одиночество", "усталость",
                       "разлука", "тревога_за_другого", "ссора", "предательство",
                       "безответная_любовь", "неудача"):
            empathy = self.get_empathy_response(emotion, lang)
            if empathy:
                return empathy
            if lang == "en":
                return random.choice(self.p.FALLBACK_RESPONSES_EN)

        if emotion == "радость":
            empathy = self.get_empathy_response("радость", lang)
            if empathy:
                return empathy
            if lang == "en":
                return "That's wonderful! I'm so happy for you! 🎉 Tell me more!"

        if friendly:
            return friendly

        if "расскажи истори" in message_lower or "история" in message_lower or "story" in message_lower:
            return self.tell_story()
        if message_lower in ("игра", "играть", "game"):
            return self.start_game(lang)
        if message_lower in ("подсказка", "hint"):
            return self.give_hint(lang)

        if self.game_active and self.current_character is not None:
            if not (
                message_lower in self.p.NON_GAME_COMMANDS
                or "помоги" in message_lower
                or "help" in message_lower
                or "расскажи истори" in message_lower
                or "история" in message_lower
                or "story" in message_lower
            ):
                return self.check_guess(message, lang)

        if "помоги" in message_lower or "help" in message_lower:
            return self.get_advice(message, lang)

        if message_lower in ("привет", "hello", "hi", "здравствуй", "здравствуйте"):
            if lang == "en":
                return self.p.GREETING_RESPONSE_EN
            return self.p.GREETING_RESPONSE
        if message_lower in ("пока", "bye", "goodbye", "до свидания", "прощай"):
            if lang == "en":
                return self.p.FAREWELL_RESPONSE_EN
            return self.p.FAREWELL_RESPONSE
        if message_lower in ("дата", "date"):
            return f"📅 ДАТА: {datetime.datetime.now().date()}"
        if message_lower in ("время", "time"):
            return f"🕐 ВРЕМЯ: {datetime.datetime.now().time().strftime('%H:%M:%S')}"
        if message_lower in ("картинка", "picture", "image"):
            return f'<img src="{self.p.IMG_URL}" alt="Аватарка бота" style="max-width: 300px; border-radius: 10px;">'
        if message_lower in ("шутка", "анекдот", "joke"):
            joke = self.get_joke_from_internet()
            return f"😂 {joke}"

        if lang == "en":
            return random.choice(self.p.FALLBACK_RESPONSES_EN)

        return random.choice(self.p.FALLBACK_RESPONSES)


