# Смайлики и маркеры грусти / слёз
SAD_MARKERS = [
    "😢", "😭", "😔", "😞", "😟", "😥", "😿", "💔", "🥺"
]

# Маркеры серьёзности / срочности
SERIOUS_MARKERS = [
    "пожалуйста", "помогите", "мне плохо", "мне очень плохо",
    "очень тяжело", "не могу больше", "нет сил", "срочно"
]


def _normalize(text):
    """Убирает лишние пробелы и приводит к нижнему регистру."""
    return re.sub(r"\s+", " ", text.lower().strip())


def _has_any(text, words):
    return any(w in text for w in words)


def _is_laughing(text):
    """Определяет, шутит ли человек (смеётся)."""
    t = _normalize(text)
    # Смайлики смеха
    if _has_any(t, LAUGH_MARKERS):
        # Но если рядом есть смайлик грусти — всё же грусть
        if _has_any(t, SAD_MARKERS):
            return False
        return True
    # Смех в тексте: "ахаха", "хахаха", "хехе"
    if re.search(r"(а?ха){2,}|(хе){2,}|(хо){2,}|(хи){2,}", t):
        return True
    return False


def _is_serious(text):
    """Определяет, серьёзный ли тон (даже если есть смайлик)."""
    t = _normalize(text)
    if _has_any(t, SERIOUS_MARKERS):
        return True
    # Много восклицательных знаков + ключевые слова боли
    if t.count("!") >= 2 and _has_any(t, ["плохо", "больно", "тяжело", "страшно", "умер", "потерял"]):
        return True
    return False


def _has_negation(text, word):
    """Проверяет, есть ли отрицание перед словом (не умер, не грустно и т.п.)."""
    pattern = r"(не|ни|без)\s+\w{0,5}\s*" + re.escape(word)
    return re.search(pattern, text) is not None


def detect_emotion(message):
    """Определяет тон/эмоцию сообщения с учётом контекста и шутливого тона."""
    m = _normalize(message)

    # 0. Если человек явно шутит — не сочувствуем
    if _is_laughing(m):
        return None

    # 1. Если тон серьёзный — проверяем эмоции в первую очередь
    serious = _is_serious(m)

    # 2. Потеря / смерть / утрата — только если нет отрицания и это не шутка
    loss_words = [
        "умер", "умерла", "умерло", "умерли", "смерть", "похорон",
        "скончал", "погиб", "погибла", "похоронил", "похоронила",
        "не стало", "ушёл из жизни", "ушла из жизни"
    ]
    for w in loss_words:
        if w in m and not _has_negation(m, w):
            return "потеря"

    # "потерял(а)" — только если речь о человеке/питомце/важном,
    # а не о ключах/телефоне
    if re.search(r"потерял[аи]?\s+(?:мам|пап|брат|сестр|сын|доч|жен|муж|друг|подруг|кошк|собак|питомц|бабушк|дедушк|ребен|ребён)", m):
        return "потеря"

    # 3. Одиночество — уточнённые слова (убрано просто "одна")
    lonely_words = [
        "одинок", "одинока", "никому не нужен", "никому не нужна",
        "нет друзей", "все отвернулись", "меня бросили",
        "я одна", "я один ", "я совсем один", "я совсем одна"
    ]
    if _has_any(m, lonely_words):
        return "одиночество"

    # 4. Тревога
    anxiety_words = [
        "тревог", "боюсь", "страшно", "паника", "паникую", "нервничаю",
        "переживаю", "волнуюсь", "не могу успокоиться", "напряж"
    ]
    if _has_any(m, anxiety_words):
        return "тревога"

    # 5. Злость
    anger_words = [
        "злюсь", "злой", "злая", "бесит", "ненавижу", "раздраж", "ярость",
        "несправедлив", "достал", "достала", "надоел", "надоела",
        "выхожу из себя"
    ]
    if _has_any(m, anger_words):
        return "злость"

    # 6. Усталость
    tired_words = ["устал", "устала", "вымот", "нет сил", "истощ", "выгор", "замучил", "замучила"]
    if _has_any(m, tired_words):
        return "усталость"

    # 7. Грусть
    sad_words = [
        "груст", "печаль", "тоск", "плачу", "плакал", "плакала", "слёзы", "слезы",
        "расстроен", "расстроена", "плохо на душе", "тяжело на душе", "депресс",
        "уныл", "поник", "опустились руки", "нет настроения"
    ]
    if _has_any(m, sad_words):
        # Проверяем отрицание "не грустно"
        for w in sad_words:
            if w in m and not _has_negation(m, w):
                return "грусть"

    # 8. Радость — только если НЕ серьёзный тон и НЕ грусть
    joy_words = [
        "рад", "рада", "счастлив", "счастлива", "ура", "отлично", "супер",
        "класс", "здорово", "восторг", "праздник", "получилось", "удалось",
        "поздрав", "улыбка", "хорошее настроение", "воодушев"
    ]
    if _has_any(m, joy_words) and not serious:
        return "радость"

    return None


