    def get_friendly_response(self, message_lower: str, lang: str = "ru"):
        t = self._normalize(message_lower)

        # ── Спец-обработка: "люблю + кого-то/что-то" ──
        has_love_ru = re.search(r"\bлюблю\b", t) is not None
        has_love_en = re.search(r"\blove\b", t) is not None
        if has_love_ru or has_love_en:
            if re.search(r"\bлюблю\s+тебя\b", t) or re.search(r"\bi\s+love\s+you\b", t):
                if lang == "en":
                    return random.choice(self.p.FRIENDLY_RESPONSES_EN["люблю тебя"])
                return random.choice(self.p.FRIENDLY_RESPONSES["люблю тебя"])
            if re.search(r"\bлюблю\s+(свою|своего|свой|своих|мою|моего|мой|моих|my)\b", t) \
               or re.search(r"\blove\s+my\b", t):
                if lang == "en":
                    return random.choice(self.p.FRIENDLY_RESPONSES_EN["люблю_кого_то"])
                return random.choice(self.p.FRIENDLY_RESPONSES["люблю_кого_то"])
            if lang == "en":
                return random.choice(self.p.FRIENDLY_RESPONSES_EN["люблю_кого_то"])
            return random.choice(self.p.FRIENDLY_RESPONSES["люблю_кого_то"])

        # ── Обычные триггеры ──
        for topic, triggers in self.p.FRIENDLY_TRIGGERS.items():
            for trigger in triggers:
                pattern = r"(^|\s)" + re.escape(trigger) + r"($|\s|[,.!?;:])"
                if re.search(pattern, t):
                    if lang == "en":
                        return random.choice(self.p.FRIENDLY_RESPONSES_EN[topic])
                    return random.choice(self.p.FRIENDLY_RESPONSES[topic])
        return None

    @staticmethod
    def is_similar(text1: str, text2: str, threshold: float = 0.7):
        text1 = text1.strip().lower()
        text2 = text2.strip().lower()
        if text1 == text2:
            return True, 1.0
        if text1 in text2 or text2 in text1:
            return True, 0.9
        similarity = SequenceMatcher(None, text1, text2).ratio()
        return similarity >= threshold, similarity

